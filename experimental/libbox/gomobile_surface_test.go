package libbox

// # Why this test exists
//
// Every exported method of a gomobile-bound type (and every exported package-level
// function) is reachable from Java/Kotlin and from Objective-C/Swift through a
// generated cgo boundary. cmd/cgo writes that boundary as `//export proxy<pkg>_<Type>_<Method>`
// and, because a Go function can only return one value plus an error, it packs the
// results into a C struct that the Go side fills in through a pointer handed over by
// the caller:
//
//	//export proxylibbox_Thing_GetName
//	func proxylibbox_Thing_GetName(refnum C.int32_t) (C.nstring, C.int32_t) { ... }
//
//	// _cgo_export.c, generated by cmd/cgo
//	struct proxylibbox_Thing_GetName_return { nstring r0; int32_t r1; };
//	...
//	typedef struct {
//		int32_t recv;
//		char __pad0[4];
//		nstring r0;
//		int32_t r1;
//	} __attribute__((__packed__)) _cgo_argtype;
//	_cgo_argtype _cgo_a = _cgo_zero;                 // a LOCAL, therefore byte-aligned
//	crosscall2(_cgoexp_..., &_cgo_a, 28, _cgo_ctxt);
//
// `nstring` is `struct { void *chars; ptrdiff_t len; }` and `nbyteslice` is
// `struct { void *ptr; ptrdiff_t len; }`: both carry a Go/C pointer in the frame. On
// the Go side cgo generates
//
//	func _cgoexp_..._proxylibbox_Thing_GetName(a *struct {
//		recv int32
//		r0   _Ctype_nstring
//		r1   _Ctype_int32_t
//	}) { a.r0, a.r1 = proxylibbox_Thing_GetName(a.recv); _cgoCheckResult(a.r0) }
//
// so the Go runtime stores a pointer into a C frame that cmd/cgo declares with
// __attribute__((packed)) - i.e. with alignment 1, not 8. Go <= 1.25 does that with a
// write barrier, and when the barrier degrades to runtime.typedmemmove ->
// runtime.bulkBarrierPreWrite (the shape it picks depends on the compiler's lowering of
// the aggregate store, not on anything in this repository), bulkBarrierPreWrite throws
//
//	fatal error: bulkBarrierPreWrite: unaligned arguments
//
// the moment the C frame happens to land off an 8-byte boundary. That is a runtime
// THROW, not a panic: it unwinds nothing, it cannot be recovered, and it kills the
// process. See https://github.com/golang/go/issues/46893 and the fix that finally landed
// for Go 1.26 (CL 692935, commit d5b950399), which changes exactly this typedef to
// `__attribute__((packed, aligned(N)))`. Our toolchain (go1.25.5) predates that fix.
//
// # What this check flags, and what it deliberately does not
//
// Flagged: an exported method (or package-level function) whose RESULT is `string`,
// `[]byte`, or a locally declared named type whose underlying kind is one of those. Those
// are the only result types that put a pointer into the packed result frame; every other
// shape gomobile accepts (`*X` bound object, interface/iterator, scalar, error) becomes
// int32_t, and a struct result is not bindable at all.
//
// Not flagged, on purpose:
//   - STRUCT FIELDS. An exported field produces its own `..._<Field>_Get`/`_Set`
//     `//export` function, which is a different declaration from a method and has a
//     one-pointer-word frame. This test walks method declarations and never looks at
//     struct fields, so it does not flag the accessor of StringBox - the very workaround
//     (experimental/libbox/panic.go) that this project uses for the flagged shape.
//   - Unexported methods, and methods on unexported types: gomobile never binds them.
//   - Methods whose signature gomobile rejects (unexported parameter/result types, and
//     named types whose underlying kind is neither pointer nor interface): cmd/gobind
//     prints "// skipped method ... with unsupported parameter or return types" and the
//     method simply never reaches the platform. Note that a named STRING type falls in
//     this bucket today, which is why it is flagged rather than excused: either it stays
//     unbound (a silently missing API) or a future gobind starts binding it and it
//     becomes a bare string result frame.
//
// # The baseline is a debt register, not an exemption
//
// libbox already ships the flagged shape in a number of places (see
// gomobileResultDebt). They are grandfathered so that this check can be green today and
// still catch the NEXT one; the task this test exists for is "no NEW dangerous result
// signature". The register is checked in both directions: a flagged declaration that is
// not listed fails, AND a listed declaration that no longer exists (or is no longer
// flagged) fails, so the list can only shrink and cannot rot into a mute allowlist. Each
// entry carries the concrete reason it was not converted, and the dominant reason is that
// converting it changes a signature that a shipped client calls or implements today.
//
// # Apple vs Android
//
// The check is platform-neutral: it reads Go source with go/parser, so it makes no
// assumption about GOOS, GOARCH, build tags, or the binding language. That is also the
// honest answer to "does the same risk exist on Apple": the packed `_cgo_argtype` is
// emitted by cmd/cgo's writeExports, which is shared by -lang=java and -lang=objc - the
// Objective-C binding calls the exact same `//export proxy...` symbols, and
// objc/seq_darwin.h's `nstring` has the same `{void *, NSUInteger}` layout. The original
// reports on golang/go#46893 were iOS crashes. So the hazard is a property of the toolchain
// plus the platform C compiler's frame layout on arm64, not of Android; Android/arm64 is
// simply where it has been observed most. What I could NOT verify here is whether any
// specific existing declaration actually throws on a device: that depends on the frame
// offset clang chooses and on the Go compiler's barrier lowering, neither of which is
// visible from the source. This check therefore reasons about the shape that the Go team's
// own alignment fix (and its test matrix, which includes a plain `ReturnString`) treats as
// alignment-sensitive, rather than pretending to prove a crash per method.

