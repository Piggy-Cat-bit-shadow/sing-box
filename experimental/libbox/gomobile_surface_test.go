// gomobileResultClass is the classification of one result type for exactly the question
// this tripwire asks: does the C result frame carry a pointer?
type gomobileResultClass int

const (
	gomobileResultScalar gomobileResultClass = iota
	gomobileResultError
	gomobileResultBoundRef    // *T: gomobile passes an int32_t refnum, no pointer
	gomobileResultInterface   // a bound/external interface: also a refnum
	gomobileResultString      // string -> C.nstring{void*, len}
	gomobileResultBytes       // []byte -> C.nbyteslice{void*, len}
	gomobileResultNamedString // a local named type whose underlying kind is string
	gomobileResultNamedBytes  // a local named type whose underlying kind is []byte
	gomobileResultUnsupported // gobind rejects the signature and skips the method
	gomobileResultUnresolved  // named type declared outside this package
)

// pointerBearing reports whether the class puts a Go pointer in the packed result frame.
func (c gomobileResultClass) pointerBearing() bool {
	switch c {
	case gomobileResultString, gomobileResultBytes, gomobileResultNamedString, gomobileResultNamedBytes:
		return true
	}
	return false
}

func (c gomobileResultClass) String() string {
	switch c {
	case gomobileResultScalar:
		return "scalar"
	case gomobileResultError:
		return "error"
	case gomobileResultBoundRef:
		return "bound object (*T -> refnum)"
	case gomobileResultInterface:
		return "interface/iterator (refnum)"
	case gomobileResultString:
		return "bare string"
	case gomobileResultBytes:
		return "bare []byte"
	case gomobileResultNamedString:
		return "named string type"
	case gomobileResultNamedBytes:
		return "named []byte type"
	case gomobileResultUnsupported:
		return "unsupported by gobind (method is skipped)"
	case gomobileResultUnresolved:
		return "external named type (unresolvable from source; never pointer-bearing)"
	}
	return "unknown"
}

// gomobileSurfaceEntry is one exported declaration gomobile reaches: a method on a bound
// type (struct methods and interface methods alike - gomobile emits the same //export
// wrapper for both) or a package-level function. Struct fields are intentionally absent.
type gomobileSurfaceEntry struct {
	owner     string // bound type name; empty for a package-level function
	name      string
	isIface   bool
	results   []string
	classes   []gomobileResultClass
	position  string
	methodStr string // source-level signature, for messages
}

func (e gomobileSurfaceEntry) key() string {
	if e.owner == "" {
		return e.name
	}
	return e.owner + "." + e.name
}

// frameReason describes the flagged result the way the failure message needs it.
func (e gomobileSurfaceEntry) flaggedResults() []string {
	var flagged []string
	for i, class := range e.classes {
		if class.pointerBearing() {
			flagged = append(flagged, fmt.Sprintf("%s (%s)", e.results[i], class))
		}
	}
	return flagged
}

// summary renders the class column of the inventory: every result of the declaration,
// with the flagged ones called out in full.
func (e gomobileSurfaceEntry) summary() string {
	if len(e.classes) == 0 {
		return "void"
	}
	parts := make([]string, 0, len(e.classes))
	for i, class := range e.classes {
		if class.pointerBearing() {
			parts = append(parts, "BARE STRING/BYTES RESULT ("+e.results[i]+")")
			continue
		}
		parts = append(parts, class.String())
	}
	return strings.Join(parts, " + ")
}

