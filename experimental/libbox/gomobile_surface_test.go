// debtCallSites renders the reason together with the shipped call sites a conversion has to
// move. Recording them per entry is the point of this sweep: "a shipped client calls it" was
// true for most entries but told the next reader nothing they could act on.
func debtCallSites(reason string, callSites ...string) string {
	if len(callSites) == 0 {
		return reason
	}
	return reason + " Shipped call sites that must move with it: " + strings.Join(callSites, "; ") + "."
}

// TestGomobileMethodResultSurface is the tripwire. It walks the source of this package,
// derives the gomobile-reachable surface, and fails when a declaration carries a
// pointer-bearing result frame that the register does not account for.
func TestGomobileMethodResultSurface(t *testing.T) {
	entries := scanGomobileSurface(t, ".")

	existing := make(map[string]bool, len(entries))
	flagged := make(map[string]bool)
	for _, entry := range entries {
		existing[entry.key()] = true
		if len(entry.flaggedResults()) > 0 {
			flagged[entry.key()] = true
		}
	}

	var offenders []gomobileSurfaceEntry
	for _, entry := range entries {
		if len(entry.flaggedResults()) == 0 {
			continue
		}
		if _, registered := gomobileResultDebt[entry.key()]; registered {
			continue
		}
		offenders = append(offenders, entry)
	}

	// Fail first on anything new, with the full explanation, because that is the case a
	// developer hitting this needs to understand.
	for _, entry := range offenders {
		kind := "function"
		if entry.owner != "" {
			kind = "method"
			if entry.isIface {
				kind = "interface method"
			}
		}
		t.Errorf(`new gomobile result frame carries a Go pointer: %s %s
  declared at %s
  result: %s
  frame slot: %s

  gomobile reaches this through an //export function whose C result frame is packed
  (__attribute__((packed)) => alignment 1) and holds nstring/nbyteslice, i.e. a raw
  pointer. The Go side stores that pointer through the C frame with a write barrier, and
  when the barrier lowers to runtime.typedmemmove -> runtime.bulkBarrierPreWrite on a
  frame that is not 8-byte aligned the runtime THROWS:

      fatal error: bulkBarrierPreWrite: unaligned arguments

  That is a throw, not a panic: the process is killed and nothing can recover it. Go
  1.26 aligns this frame (cmd/cgo CL 692935); the toolchain pinned here does not.

  Return a bound object instead of the raw value, exactly as the rest of this package
  does:
    - string  -> *StringBox, built with wrapString(), read through its Value accessor
                 (experimental/libbox/panic.go; precedent: TunOptions.GetDNSMode)
    - []byte or a list -> an existing ...Iterator type (precedent: TunOptions.GetDNSServerAddress)
    - several fields -> a *SomeResult struct with accessors
  If the signature genuinely cannot change because a shipped client calls it, add the key
  %q to gomobileResultDebt WITH the reason, and make it a planned migration.`,
			kind, entry.methodStr, entry.position, strings.Join(entry.results, ", "),
			strings.Join(entry.flaggedResults(), ", "), entry.key())
	}

	// The register is a debt register: it must not outlive the code it describes, and it
	// must not claim a declaration that is no longer flagged.
	var stale []string
	for key, reason := range gomobileResultDebt {
		switch {
		case !existing[key]:
			stale = append(stale, fmt.Sprintf("%s: no such bound declaration any more (%s)", key, reason))
		case !flagged[key]:
			stale = append(stale, fmt.Sprintf("%s: exists but no longer has a pointer-bearing result (%s)", key, reason))
		}
	}
	sort.Strings(stale)
	for _, entry := range stale {
		t.Errorf("gomobileResultDebt is stale: %s\ndelete the entry - the register may only shrink", entry)
	}

	var boundCount = len(entries)
	t.Logf("gomobile surface: %d bound declarations, %d with a pointer-bearing result (%d registered as debt)",
		boundCount, len(flagged), len(gomobileResultDebt))

	// The complete inventory. It is logged rather than asserted: `go test -v -run
	// TestGomobileMethodResultSurface ./experimental/libbox` is what a reviewer or a
	// downstream platform author runs to see the whole bound surface and its classes
	// without reading the source.
	if testing.Verbose() {
		var inventory strings.Builder
		inventory.WriteString("\ntype | method | result type | class\n")
		for _, entry := range entries {
			typeColumn := entry.owner
			if typeColumn == "" {
				typeColumn = "(package function)"
			}
			resultColumn := "(none)"
			if len(entry.results) > 0 {
				resultColumn = strings.Join(entry.results, ", ")
			}
			fmt.Fprintf(&inventory, "%s | %s | %s | %s\n", typeColumn, entry.name, resultColumn, entry.summary())
		}
		t.Log(inventory.String())
	}
}

// scanGomobileSurface parses this package's source (all non-test .go files, including
// files excluded by the current build tags, so that an Android-only declaration is still
// seen from a macOS checkout) and mirrors cmd/gobind's own reachability rules:
//
//   - every exported local type whose underlying type is a struct or an interface is
//     bound; interfaces contribute their method set, structs contribute their exported
//     methods (methods declared with a value or a pointer receiver);
//   - every exported package-level function is bound;
//   - nothing else is.
//
// It is a source-level check on purpose: it must stay platform-neutral and must not add
// a dependency (golang.org/x/tools/go/packages would turn an indirect requirement into a
// direct one). The cost is that named types declared outside this package cannot be
// resolved; that is fine, because gomobile rejects such a result unless its underlying
// kind is a pointer or an interface, and both are refnums either way.
func scanGomobileSurface(t *testing.T, dir string) []gomobileSurfaceEntry {
	t.Helper()

	fileSet := token.NewFileSet()
	var parsed []*ast.File
	dirEntries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatalf("read package directory: %v", err)
	}
	for _, dirEntry := range dirEntries {
		name := dirEntry.Name()
		if dirEntry.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		file, err := parser.ParseFile(fileSet, filepath.Join(dir, name), nil, parser.SkipObjectResolution)
		if err != nil {
			t.Fatalf("parse %s: %v", name, err)
		}
		parsed = append(parsed, file)
	}
	if len(parsed) == 0 {
		t.Fatal("no package sources found to scan")
	}

	// Local type declarations, so that `type X string` and `type X Y` chains resolve and
	// so that `type A B` where B is a struct is still recognised as a bound struct.
	localTypes := make(map[string][]ast.Expr)
	for _, file := range parsed {
		for _, decl := range file.Decls {
			genDecl, ok := decl.(*ast.GenDecl)
			if !ok || genDecl.Tok != token.TYPE {
				continue
			}
			for _, spec := range genDecl.Specs {
				typeSpec := spec.(*ast.TypeSpec)
				localTypes[typeSpec.Name.Name] = append(localTypes[typeSpec.Name.Name], typeSpec.Type)
			}
		}
	}

	// resolveShape walks local named types down to the shape cmd/gobind would see. It
	// returns one of: interface, struct, string, bytes, scalar, error, pointer, external,
	// or unsupported. `unsupported` means gobind's isSupported() rejects the type, so the
	// whole declaration is skipped rather than bound.
	var resolveShape func(expr ast.Expr, depth int) string
	resolveShape = func(expr ast.Expr, depth int) string {
		if depth > 16 {
			return "unsupported"
		}
		switch typed := expr.(type) {
		case *ast.Ident:
			switch typed.Name {
			case "string":
				return "string"
			case "error":
				return "error"
			case "bool", "int", "int8", "int16", "int32", "int64",
				"uint", "uint8", "uint16", "uint32", "uint64", "uintptr",
				"float32", "float64", "rune", "byte":
				return "scalar"
			}
			variants, local := localTypes[typed.Name]
			if !local {
				return "external"
			}
			// Prefer the most dangerous variant: build-tag variants of the same name must
			// never be allowed to hide a pointer-bearing kind behind a safe sibling.
			resolved := "unsupported"
			for _, variant := range variants {
				shape := resolveShape(variant, depth+1)
				switch {
				case shape == "string" || shape == "bytes":
					return shape
				case shape == "interface" || shape == "struct" || shape == "pointer" || shape == "scalar":
					resolved = shape
				}
			}
			return resolved
		case *ast.StarExpr:
			return "pointer"
		case *ast.SelectorExpr:
			// Declared in another package: gomobile needs a pointer or interface
			// underlying type to accept it, and a pointer/interface is a refnum.
			return "external"
		case *ast.ArrayType:
			// Only the predeclared []byte/[]uint8 binds (as C.nbyteslice); cmd/gobind
			// matches on the element's *types.Basic kind, so []MyByte is rejected too.
			if typed.Len != nil {
				return "unsupported"
			}
			if isByteIdent(typed.Elt) {
				return "bytes"
			}
			return "unsupported"
		case *ast.InterfaceType:
			return "interface"
		case *ast.StructType:
			return "struct"
		case *ast.MapType, *ast.ChanType, *ast.FuncType, *ast.Ellipsis:
			return "unsupported"
		}
		return "unsupported"
	}

	// boundShape decides whether an exported type is bound at all.
	boundShapes := make(map[string]string)
	for name := range localTypes {
		if !ast.IsExported(name) {
			continue
		}
		shape := resolveShape(ast.NewIdent(name), 0)
		if shape == "struct" || shape == "interface" {
			boundShapes[name] = shape
		}
	}

	classify := func(expr ast.Expr) (gomobileResultClass, string) {
		switch resolveShape(expr, 0) {
		case "string":
			// The bare predeclared string, versus `type Foo string` used as a result.
			if ident, direct := expr.(*ast.Ident); direct && ident.Name == "string" {
				return gomobileResultString, "string"
			}
			return gomobileResultNamedString, "named string"
		case "bytes":
			if _, direct := expr.(*ast.ArrayType); direct {
				return gomobileResultBytes, "[]byte"
			}
			return gomobileResultNamedBytes, "named []byte"
		case "error":
			return gomobileResultError, "error"
		case "scalar":
			return gomobileResultScalar, "scalar"
		case "pointer":
			return gomobileResultBoundRef, "bound object"
		case "interface":
			return gomobileResultInterface, "interface"
		case "struct":
			// A struct result is not bindable: cmd/gobind skips the declaration.
			return gomobileResultUnsupported, "struct value"
		case "external":
			return gomobileResultUnresolved, "external named type"
		}
		return gomobileResultUnsupported, "unsupported"
	}

	var entries []gomobileSurfaceEntry
	record := func(owner, name string, isIface bool, funcType *ast.FuncType, position token.Position) {
		entry := gomobileSurfaceEntry{
			owner:    owner,
			name:     name,
			isIface:  isIface,
			position: position.String(),
		}
		if owner == "" {
			entry.methodStr = name
		} else {
			entry.methodStr = owner + "." + name
		}
		if funcType.Results == nil {
			entries = append(entries, entry)
			return
		}
		for _, result := range funcType.Results.List {
			repeats := len(result.Names)
			if repeats == 0 {
				repeats = 1
			}
			class, rendered := classify(result.Type)
			for i := 0; i < repeats; i++ {
				entry.results = append(entry.results, rendered)
				entry.classes = append(entry.classes, class)
			}
		}
		entries = append(entries, entry)
	}

	// Interface method sets, including embedded interfaces, because gomobile generates an
	// //export wrapper for every method in the set.
	var interfaceMethods func(name string, seen map[string]bool) []*ast.Field
	interfaceDecls := make(map[string]*ast.InterfaceType)
	for _, file := range parsed {
		for _, decl := range file.Decls {
			genDecl, ok := decl.(*ast.GenDecl)
			if !ok || genDecl.Tok != token.TYPE {
				continue
			}
			for _, spec := range genDecl.Specs {
				typeSpec := spec.(*ast.TypeSpec)
				if interfaceType, ok := typeSpec.Type.(*ast.InterfaceType); ok {
					interfaceDecls[typeSpec.Name.Name] = interfaceType
				}
			}
		}
	}
	interfaceMethods = func(name string, seen map[string]bool) []*ast.Field {
		if seen[name] {
			return nil
		}
		seen[name] = true
		interfaceType, ok := interfaceDecls[name]
		if !ok || interfaceType.Methods == nil {
			return nil
		}
		var fields []*ast.Field
		for _, field := range interfaceType.Methods.List {
			if _, isFunc := field.Type.(*ast.FuncType); isFunc {
				fields = append(fields, field)
				continue
			}
			embedded := typeName(field.Type)
			if embedded == "" {
				continue
			}
			fields = append(fields, interfaceMethods(embedded, seen)...)
		}
		return fields
	}

	for _, file := range parsed {
		for _, decl := range file.Decls {
			switch typed := decl.(type) {
			case *ast.FuncDecl:
				if !ast.IsExported(typed.Name.Name) {
					continue
				}
				if typed.Recv == nil || len(typed.Recv.List) == 0 {
					record("", typed.Name.Name, false, typed.Type, fileSet.Position(typed.Pos()))
					continue
				}
				owner := typeName(typed.Recv.List[0].Type)
				if _, bound := boundShapes[owner]; !bound {
					continue
				}
				record(owner, typed.Name.Name, boundShapes[owner] == "interface", typed.Type, fileSet.Position(typed.Pos()))
			case *ast.GenDecl:
				if typed.Tok != token.TYPE {
					continue
				}
				for _, spec := range typed.Specs {
					typeSpec := spec.(*ast.TypeSpec)
					if !ast.IsExported(typeSpec.Name.Name) {
						continue
					}
					if _, bound := boundShapes[typeSpec.Name.Name]; !bound {
						continue
					}
					if _, isInterface := typeSpec.Type.(*ast.InterfaceType); !isInterface {
						continue
					}
					for _, field := range interfaceMethods(typeSpec.Name.Name, make(map[string]bool)) {
						funcType, ok := field.Type.(*ast.FuncType)
						if !ok {
							continue
						}
						for _, methodName := range field.Names {
							if !ast.IsExported(methodName.Name) {
								continue
							}
							record(typeSpec.Name.Name, methodName.Name, true, funcType, fileSet.Position(methodName.Pos()))
						}
					}
				}
			}
		}
	}

	sort.Slice(entries, func(i, j int) bool {
		if entries[i].key() != entries[j].key() {
			return entries[i].key() < entries[j].key()
		}
		return entries[i].position < entries[j].position
	})
	return entries
}

// typeName renders the named type behind a receiver or an embedded interface entry,
// unwrapping pointers and generic instantiation.
func typeName(expr ast.Expr) string {
	switch typed := expr.(type) {
	case *ast.Ident:
		return typed.Name
	case *ast.StarExpr:
		return typeName(typed.X)
	case *ast.IndexExpr:
		return typeName(typed.X)
	case *ast.IndexListExpr:
		return typeName(typed.X)
	}
	return ""
}

// isByteIdent reports whether the element type of a slice is byte/uint8, which is the
// only slice kind gomobile binds (as C.nbyteslice).
func isByteIdent(expr ast.Expr) bool {
	ident, ok := expr.(*ast.Ident)
	if !ok {
		return false
	}
	return ident.Name == "byte" || ident.Name == "uint8"
}
